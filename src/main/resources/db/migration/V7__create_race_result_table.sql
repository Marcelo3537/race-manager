CREATE TABLE race_result (
    id              BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    race_id         BIGINT      NOT NULL,
    entry_id        BIGINT      NOT NULL,
    position        INTEGER,
    points          INTEGER     NOT NULL DEFAULT 0,
    laps_completed  INTEGER     NOT NULL DEFAULT 0,
    fastest_lap     BOOLEAN     NOT NULL DEFAULT FALSE,
    status          VARCHAR(20) NOT NULL,

    CONSTRAINT fk_result_race FOREIGN KEY (race_id)
        REFERENCES race (id) ON DELETE RESTRICT,

    CONSTRAINT fk_result_entry FOREIGN KEY (entry_id)
        REFERENCES championship_entry (id) ON DELETE RESTRICT,

    CONSTRAINT uk_result_race_entry UNIQUE (race_id, entry_id),
    CONSTRAINT uk_result_race_position UNIQUE (race_id, position),

    CONSTRAINT ck_result_position CHECK (position IS NULL OR position > 0),
    CONSTRAINT ck_result_points CHECK (points >= 0),
    CONSTRAINT ck_result_laps CHECK (laps_completed >= 0),
    CONSTRAINT ck_result_status CHECK (status IN ('FINISHED', 'DNF', 'DNS', 'DSQ')),
    CONSTRAINT ck_result_position_matches_status CHECK (
        (status = 'FINISHED' AND position IS NOT NULL)
        OR (status <> 'FINISHED' AND position IS NULL)
    )
);

CREATE INDEX idx_result_entry ON race_result (entry_id);

CREATE UNIQUE INDEX uk_result_fastest_lap
    ON race_result (race_id) WHERE fastest_lap = true;